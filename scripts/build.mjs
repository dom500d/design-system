// Inlines src/index.css into one file that a static site can link directly.
// No dependencies, so a project can use the kit without a build step of its own.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'src/index.css');
const { version } = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));

const source = readFileSync(entry, 'utf8');
const output = source.replace(
  /^@import "(.+?)" layer\((.+?)\);$/gm,
  (_, path, layer) => {
    const css = readFileSync(resolve(dirname(entry), path), 'utf8').trim();
    return `@layer ${layer} {\n${css}\n}\n`;
  },
);

if (output.includes('@import')) throw new Error('Unresolved @import in src/index.css');

mkdirSync(resolve(root, 'dist'), { recursive: true });
writeFileSync(resolve(root, 'dist/sectional.css'), `/* Sectional ${version} */\n${output}`);
console.log(`Built dist/sectional.css (${(output.length / 1024).toFixed(1)} KB)`);

// Typed layer. tokens.css stays the single source: everything below is read
// from it, so a token or class that exists in CSS exists in TypeScript.
const tokensCss = readFileSync(resolve(root, 'src/tokens.css'), 'utf8');
const declarations = (block) =>
  [...block.matchAll(/--ds-([a-z0-9-]+):\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]);
const block = (start) => {
  const from = tokensCss.indexOf(start);
  if (from < 0) throw new Error(`Missing ${start} in tokens.css`);
  return tokensCss.slice(from, tokensCss.indexOf('}', from));
};

const key = (name) =>
  /^\d+$/.test(name) ? `space${name}` : name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const lightTokens = declarations(block(':root {'));
const darkTokens = new Map(declarations(block(":root[data-theme='dark'] {")));
const names = lightTokens.map(([name]) => name);
for (const name of darkTokens.keys()) {
  if (!names.includes(name)) throw new Error(`--ds-${name} has no light value`);
}

const classes = [...new Set([...output.matchAll(/\.(ds-[a-zA-Z0-9_-]+)/g)].map((m) => m[1]))].sort();

const lit = JSON.stringify;
const object = (entries) => `{\n${entries.map(([k, v]) => `  ${k}: ${lit(v)},`).join('\n')}\n}`;
const shape = (entries) => `{\n${entries.map(([k, v]) => `  readonly ${k}: ${lit(v)};`).join('\n')}\n}`;

const varEntries = names.map((name) => [key(name), `var(--ds-${name})`]);
const lightEntries = lightTokens.map(([name, value]) => [key(name), value]);
const darkEntries = lightTokens.map(([name, value]) => [key(name), darkTokens.get(name) ?? value]);

writeFileSync(
  resolve(root, 'dist/tokens.js'),
  `// Generated by scripts/build.mjs from src/tokens.css. Do not edit.
/** CSS variable references. These follow the active theme, so prefer them. */
export const token = ${object(varEntries)};

/** Raw values, for places that cannot read CSS variables, such as canvas or map libraries. */
export const light = ${object(lightEntries)};
export const dark = ${object(darkEntries)};

/** Joins class names and skips falsy values. */
export function ds(...names) {
  return names.filter(Boolean).join(' ');
}
`,
);

writeFileSync(
  resolve(root, 'dist/tokens.d.ts'),
  `// Generated by scripts/build.mjs from src/tokens.css. Do not edit.
export declare const token: ${shape(varEntries)};
export declare const light: ${shape(lightEntries)};
export declare const dark: ${shape(darkEntries)};

/** Any token name, such as "fill" or "textSm". */
export type TokenName = keyof typeof token;

/** Any class name the kit ships. */
export type DsClass =
${classes.map((c) => `  | ${lit(c)}`).join('\n')};

/** Joins class names and skips falsy values. Unknown names are a type error. */
export declare function ds(...names: Array<DsClass | false | null | undefined>): string;
`,
);
console.log(`Built dist/tokens.js and tokens.d.ts (${names.length} tokens, ${classes.length} classes)`);
